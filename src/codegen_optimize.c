#include "../include/common.h"

/* Global optimization configuration */
static OptimizationConfig g_optim_config = {
    .optimization_level = 3,        /* Maximum optimization */
    .verbose = false,
    .benchmark = false,
    .cpu_profile = "generic",
};

/* ============================================
 * CONFIGURATION
 * ============================================ */

void codegen_optim_config_set_level(int level) {
    if (level < 0 || level > 3) {
        fprintf(stderr, "ERROR: Optimization level must be 0-3\n");
        return;
    }
    g_optim_config.optimization_level = level;
}

void codegen_optim_config_set_verbose(bool verbose) {
    g_optim_config.verbose = verbose;
}

void codegen_optim_config_enable_benchmark(bool enable) {
    g_optim_config.benchmark = enable;
}

void codegen_optim_config_set_cpu(const char *profile) {
    if (!profile) return;
    free(g_optim_config.cpu_profile);
    g_optim_config.cpu_profile = xstrdup(profile);
}

/* ============================================
 * ASSEMBLY GENERATION WITH OPTIMIZATION
 * ============================================ */

CompiledOutput codegen_generate_optimized(
    const char *source_file,
    const char *output_file,
    void *program,
    int optimization_level
) {
    (void)source_file;  /* Unused parameter */
    (void)program;      /* Unused parameter */
    
    CompiledOutput result = {0};
    
    if (optimization_level < 0 || optimization_level > 3) {
        optimization_level = 3;
    }
    
    /* Phase 1: Generate base assembly (unoptimized) */
    clock_t start_time = clock();
    
    /* Create temporary assembly file */
    char temp_asm[320];
    snprintf(temp_asm, sizeof(temp_asm), "/tmp/rascom_unopt_%d.asm", (int)getpid());
    
    /* Generate unoptimized code (using existing codegen) */
    FILE *asm_file = fopen(temp_asm, "w");
    if (!asm_file) {
        fprintf(stderr, "ERROR: Cannot open temp assembly file: %s\n", temp_asm);
        result.success = false;
        return result;
    }
    
    /* Note: We would call the actual codegen here */
    /* For now, this is a placeholder showing integration */
    
    fclose(asm_file);
    
    /* Phase 2: Read assembly and parse into instruction list */
    FILE *read_asm = fopen(temp_asm, "r");
    if (!read_asm) {
        result.success = false;
        return result;
    }
    
    const char **instructions = malloc(sizeof(char*) * 10000);
    int instr_count = 0;
    char line[512];
    
    while (fgets(line, sizeof(line), read_asm) && instr_count < 10000) {
        /* Skip empty lines and comments at start of line */
        if (line[0] == '\n' || (line[0] == ';' && line[1] != ';')) {
            continue;
        }
        
        /* Remove trailing newline */
        size_t len = strlen(line);
        if (line[len - 1] == '\n') {
            line[len - 1] = '\0';
        }
        
        instructions[instr_count] = xstrdup(line);
        instr_count++;
    }
    
    fclose(read_asm);
    result.unoptimized_instruction_count = instr_count;
    
    if (g_optim_config.verbose) {
        fprintf(stderr, "[OPTIM] Read %d instructions from base codegen\n", instr_count);
    }
    
    /* Phase 3: Apply optimization passes */
    clock_t optim_start = clock();
    
    OptimizationResult optim_result = optim_advanced_compile(
        instructions,
        instr_count,
        optimization_level
    );
    
    clock_t optim_end = clock();
    
    /* Phase 4: Write optimized assembly */
    FILE *final_asm = fopen(output_file, "w");
    if (!final_asm) {
        fprintf(stderr, "ERROR: Cannot open output file: %s\n", output_file);
        result.success = false;
        return result;
    }
    
    /* Write header comment */
    fprintf(final_asm, "; RasCode Optimized Assembly\n");
    fprintf(final_asm, "; Generated by rascom with optimization level %d\n", optimization_level);
    fprintf(final_asm, "; Optimization: %d%% reduction, %d%% speedup\n\n",
            (100 * (instr_count - optim_result.optimized_instruction_count)) / instr_count,
            (int)optim_result.estimated_speedup_percent);
    
    /* Write all optimized instructions */
    for (int i = 0; i < optim_result.optimized_instruction_count; i++) {
        fprintf(final_asm, "%s\n", optim_result.optimized_instructions[i]);
    }
    
    fclose(final_asm);
    
    /* Phase 5: Collect statistics */
    clock_t end_time = clock();
    
    result.success = true;
    result.unoptimized_instruction_count = instr_count;
    result.optimized_instruction_count = optim_result.optimized_instruction_count;
    result.instructions_eliminated = instr_count - optim_result.optimized_instruction_count;
    result.cse_eliminations = optim_result.cse_eliminations;
    result.strength_reductions = optim_result.strength_reductions;
    result.peephole_optimizations = optim_result.peephole_optimizations;
    result.bytes_saved = optim_result.bytes_saved;
    result.estimated_speedup_percent = optim_result.estimated_speedup_percent;
    result.codegen_time_ms = (double)(optim_start - start_time) * 1000.0 / CLOCKS_PER_SEC;
    result.optimization_time_ms = (double)(optim_end - optim_start) * 1000.0 / CLOCKS_PER_SEC;
    result.total_time_ms = (double)(end_time - start_time) * 1000.0 / CLOCKS_PER_SEC;
    
    /* Clean up temp file */
    remove(temp_asm);
    
    /* Free instruction buffers */
    for (int i = 0; i < instr_count; i++) {
        free((void*)instructions[i]);
    }
    free(instructions);
    
    return result;
}

/* ============================================
 * STANDALONE OPTIMIZATION
 * ============================================ */

bool codegen_optimize_asm_file(
    const char *input_file,
    const char *output_file,
    int optimization_level
) {
    /* Read assembly file */
    FILE *in = fopen(input_file, "r");
    if (!in) {
        fprintf(stderr, "ERROR: Cannot read input file: %s\n", input_file);
        return false;
    }
    
    /* Read all instructions */
    const char **instructions = malloc(sizeof(char*) * 10000);
    int count = 0;
    char line[512];
    
    while (fgets(line, sizeof(line), in) && count < 10000) {
        if (line[0] == '\n') continue;
        
        size_t len = strlen(line);
        if (line[len - 1] == '\n') line[len - 1] = '\0';
        
        instructions[count] = xstrdup(line);
        count++;
    }
    
    fclose(in);
    
    if (g_optim_config.verbose) {
        fprintf(stderr, "[OPTIM] Optimizing %d instructions from %s\n", count, input_file);
    }
    
    /* Apply optimizations */
    OptimizationResult result = optim_advanced_compile(instructions, count, optimization_level);
    
    /* Write output */
    FILE *out = fopen(output_file, "w");
    if (!out) {
        fprintf(stderr, "ERROR: Cannot write output file: %s\n", output_file);
        return false;
    }
    
    fprintf(out, "; Optimized assembly (level %d)\n", optimization_level);
    fprintf(out, "; Instructions reduced: %d -> %d (%.1f%% reduction)\n\n",
            count, result.optimized_instruction_count,
            (100.0 * (count - result.optimized_instruction_count)) / count);
    
    for (int i = 0; i < result.optimized_instruction_count; i++) {
        fprintf(out, "%s\n", result.optimized_instructions[i]);
    }
    
    fclose(out);
    
    /* Print stats if verbose */
    if (g_optim_config.verbose) {
        optim_result_print_stats(&result);
    }
    
    /* Free memory */
    for (int i = 0; i < count; i++) {
        free((void*)instructions[i]);
    }
    free(instructions);
    
    return true;
}

